export const LENORMAND_DECK: LenormandCard[] = RAW.map(([name, keywords, time], i) => ({
  id: i + 1,
  name,
  keywords,
  time,
}));

export const LENORMAND_NAMES: string[] = LENORMAND_DECK.map((c) => c.name);

/** id 1 ~ 36 → 牌名 */
export function lenormandName(id: number): string {
  return LENORMAND_NAMES[id - 1] ?? String(id);
}

export function getLenormand(id: number): LenormandCard | undefined {
  return LENORMAND_DECK[id - 1];
}
